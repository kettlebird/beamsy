# Beamsy brand assets from the Figma "App icon & TV banner" board.
# Usage (from the repo root): pip install pillow fonttools skia-pathops && python tools/make_brand_assets.py .
# Writes vector drawables (icons, TV banners) into both apps and PNGs for the Play listings.
import os, sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.basePen import BasePen
from PIL import Image, ImageChops, ImageDraw

ROOT = sys.argv[1]
# Open Sauce with overlapping contours merged: draw_text fills outlines even-odd, which needs non-overlapping contours
import tempfile
from fontTools.ttLib.removeOverlaps import removeOverlaps
_TMP = tempfile.mkdtemp()


def _clean(weight):
    font = TTFont(os.path.join(ROOT, f"app/src/main/res/font/open_sauce_sans_{weight}.ttf"))
    removeOverlaps(font)
    path = os.path.join(_TMP, f"{weight}.ttf")
    font.save(path)
    return path


BOLD = _clean("bold")
MEDIUM = _clean("medium")

# mark on a 100-unit grid: see-through phone, TV, stand, violet picture
PHONE = (58, 10, 30, 52, 8)
TV = (10, 34, 64, 42, 9)
STAND = (29, 82, 26, 6, 3)
PIC = (20, 43, 44, 24, 5)
MARK_BOX = (10, 10, 88, 88)  # drawn extent

THEMES = {
    "app": dict(bg=("#8B5CF6", "#3B0D8C"), glow="#C4B5FD"),
    "unlock": dict(bg=("#F59E0B", "#B45309"), glow="#FDE68A"),
}


def rr_path(x, y, w, h, r, s=1.0, tx=0.0, ty=0.0):
    x, y, w, h, r = x * s + tx, y * s + ty, w * s, h * s, r * s
    f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    return (f"M{f(x + r)},{f(y)}h{f(w - 2 * r)}a{f(r)},{f(r)} 0 0 1 {f(r)},{f(r)}v{f(h - 2 * r)}"
            f"a{f(r)},{f(r)} 0 0 1 -{f(r)},{f(r)}h-{f(w - 2 * r)}a{f(r)},{f(r)} 0 0 1 -{f(r)},-{f(r)}"
            f"v-{f(h - 2 * r)}a{f(r)},{f(r)} 0 0 1 {f(r)},-{f(r)}z")


def text_path(text, font_file, size, x, baseline, tracking=-0.02):
    """Glyph outlines as one SVG path, placed with its baseline at (x, baseline). Returns (path, width)."""
    font = TTFont(font_file)
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    upm = font["head"].unitsPerEm
    sc = size / upm
    pen = SVGPathPen(gs)
    cx = x
    for ch in text:
        g = cmap[ord(ch)]
        gs[g].draw(TransformPen(pen, (sc, 0, 0, -sc, cx, baseline)))
        cx += hmtx[g][0] * sc + tracking * size
    return pen.getCommands(), cx - x - tracking * size


def cap_height(font_file, size):
    font = TTFont(font_file)
    return font["OS/2"].sCapHeight * size / font["head"].unitsPerEm


def mark_paths(s, tx, ty, ink="#FFFFFF", mono=False):
    out = []
    if mono:
        # one shape: phone, TV with the picture cut out, stand
        d = rr_path(*PHONE, s=s, tx=tx, ty=ty) + rr_path(*TV, s=s, tx=tx, ty=ty) + rr_path(*PIC, s=s, tx=tx, ty=ty) + rr_path(*STAND, s=s, tx=tx, ty=ty)
        return [f'    <path android:fillColor="#000000" android:fillType="evenOdd" android:pathData="{d}" />']
    out.append(f'    <path android:fillColor="{ink}" android:fillAlpha="0.42" android:pathData="{rr_path(*PHONE, s=s, tx=tx, ty=ty)}" />')
    out.append(f'    <path android:fillColor="{ink}" android:pathData="{rr_path(*TV, s=s, tx=tx, ty=ty)}" />')
    out.append(f'    <path android:fillColor="{ink}" android:pathData="{rr_path(*STAND, s=s, tx=tx, ty=ty)}" />')
    x0, x1 = PIC[0] * s + tx, (PIC[0] + PIC[2]) * s + tx
    out.append(f'''    <path android:pathData="{rr_path(*PIC, s=s, tx=tx, ty=ty)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x0:.2f}" android:startY="0" android:endX="{x1:.2f}" android:endY="0"
                android:startColor="#7C3AED" android:endColor="#A78BFA" />
        </aapt:attr>
    </path>''')
    return out


def background_paths(w, h, theme):
    a, b = theme["bg"]
    g = theme["glow"]
    r = 0.55 * max(w, h)
    return [f'''    <path android:pathData="M0,0h{w}v{h}H0z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="{w}" android:endY="{h}"
                android:startColor="{a}" android:endColor="{b}" />
        </aapt:attr>
    </path>''', f'''    <path android:pathData="M0,0h{w}v{h}H0z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="{0.22 * w:.1f}" android:centerY="{0.12 * h:.1f}" android:gradientRadius="{r:.1f}"
                android:startColor="#73{g[1:]}" android:endColor="#00{g[1:]}" />
        </aapt:attr>
    </path>''']


def vector(w, h, body, vw=None, vh=None):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by make_assets.py from the Figma "App icon & TV banner" board -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{w}dp"\n    android:height="{h}dp"\n    android:viewportWidth="{vw or w}"\n    android:viewportHeight="{vh or h}">\n'
            + "\n".join(body) + "\n</vector>\n")


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def banner_layout(subtitle):
    # 320x180 dp, mark and wordmark centred as one lockup
    s = 0.64
    word_size = 52
    _, word_w = text_path("Beamsy", BOLD, word_size, 0, 0)
    mark_w = (MARK_BOX[2] - MARK_BOX[0]) * s
    gap = 10
    total = mark_w + gap + word_w
    x0 = (320 - total) / 2
    cap = cap_height(BOLD, word_size)
    sub_h = 18 if subtitle else 0
    block_h = max(mark_w, cap + (10 + sub_h * 0.72 if subtitle else 0))
    top = (180 - block_h) / 2
    mark_tx = x0 - MARK_BOX[0] * s
    mark_ty = top + (block_h - mark_w) / 2 - MARK_BOX[1] * s
    text_x = x0 + mark_w + gap
    baseline = top + (block_h - (cap + (10 + sub_h * 0.72 if subtitle else 0))) / 2 + cap
    return s, mark_tx, mark_ty, text_x, baseline, word_size, sub_h


for app, theme in THEMES.items():
    res = os.path.join(ROOT, app, "src/main/res/drawable")
    write(os.path.join(res, "ic_launcher_background.xml"), vector(108, 108, background_paths(108, 108, theme)))
    # adaptive foreground: the safe zone is a 66 dp circle, so the mark's corners must stay within r=33: 78 units at 0.6
    s, t = 0.6, 54 - 49 * 0.6
    write(os.path.join(res, "ic_launcher_foreground.xml"), vector(108, 108, mark_paths(s, t, t)))
    write(os.path.join(res, "ic_launcher_monochrome.xml"), vector(108, 108, mark_paths(s, t, t, mono=True)))
    subtitle = "Full HD Unlock" if app == "unlock" else None
    s, mtx, mty, tx_, base, size, sub_h = banner_layout(subtitle)
    body = background_paths(320, 180, theme) + mark_paths(s, mtx, mty)
    d, _ = text_path("Beamsy", BOLD, size, tx_, base)
    body.append(f'    <path android:fillColor="#FFFFFF" android:pathData="{d}" />')
    if subtitle:
        d2, _ = text_path(subtitle, MEDIUM, sub_h, tx_ + 2, base + 10 + sub_h * 0.72, tracking=0)
        body.append(f'    <path android:fillColor="#FFFFFF" android:fillAlpha="0.85" android:pathData="{d2}" />')
    write(os.path.join(res, "banner.xml"), vector(320, 180, body))


# ---- Play Store PNGs (drawn at 4x, then downsampled) ----
class _Flatten(BasePen):
    """Glyph outline -> list of polygons (quadratic/cubic curves flattened)."""
    def __init__(self, gs):
        super().__init__(gs); self.polys = []; self.cur = []
    def _moveTo(self, p): self.cur = [p]
    def _lineTo(self, p): self.cur.append(p)
    def _qCurveToOne(self, c, p):
        (x0, y0), n = self.cur[-1], 12
        for i in range(1, n + 1):
            t = i / n; u = 1 - t
            self.cur.append((u * u * x0 + 2 * u * t * c[0] + t * t * p[0], u * u * y0 + 2 * u * t * c[1] + t * t * p[1]))
    def _curveToOne(self, c1, c2, p):
        (x0, y0), n = self.cur[-1], 16
        for i in range(1, n + 1):
            t = i / n; u = 1 - t
            self.cur.append((u**3 * x0 + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t**3 * p[0],
                             u**3 * y0 + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t**3 * p[1]))
    def _closePath(self): self.polys.append(self.cur); self.cur = []
    _endPath = _closePath


def draw_text(img, xy, text, font_file, size, fill=(255, 255, 255, 255), anchor="ls", tracking=-0.02):
    """Fill glyph outlines directly (Pillow's FreeType path draws spurs on this font). Even-odd is fine:
    the font copy has its overlaps merged."""
    font = TTFont(font_file)
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]
    sc = size / font["head"].unitsPerEm
    width = sum(hmtx[cmap[ord(c)]][0] * sc + tracking * size for c in text) - tracking * size
    x = xy[0] - (width / 2 if anchor[0] == "m" else 0)
    mask = Image.new("L", img.size, 0)
    for ch in text:
        g = cmap[ord(ch)]
        pen = _Flatten(gs); gs[g].draw(pen)
        for poly in pen.polys:
            m = Image.new("L", img.size, 0)
            ImageDraw.Draw(m).polygon([(x + px * sc, xy[1] - py * sc) for px, py in poly], fill=255)
            mask = ImageChops.difference(mask, m)  # xor
        x += hmtx[g][0] * sc + tracking * size
    img.paste(Image.new("RGBA", img.size, fill), (0, 0), ImageChops.multiply(mask, Image.new("L", img.size, fill[3])))
    return width


def hexrgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def bg_image(w, h, theme):
    a, b = (Image.new("RGB", (w, h), hexrgb(c)) for c in theme["bg"])
    # diagonal: average of a left-to-right and a top-to-bottom ramp
    mask = ImageChops.add(Image.linear_gradient("L").resize((w, h)), Image.linear_gradient("L").rotate(90).resize((w, h)), scale=2.0)
    img = Image.composite(b, a, mask)
    glow = Image.radial_gradient("L").resize((int(1.1 * max(w, h)),) * 2)
    # radial_gradient reaches only ~180 at the square's edges: stretch so it fades to 0 before them
    glow = glow.point(lambda v: int(max(0, 255 - v * 1.45) * 0.45))
    layer = Image.new("RGB", glow.size, hexrgb(theme["glow"]))
    gx, gy = int(0.22 * w - glow.size[0] / 2), int(0.12 * h - glow.size[1] / 2)
    img.paste(layer, (gx, gy), glow)
    return img


def draw_mark(img, s, tx, ty):
    over = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(over)
    box = lambda x, y, w, h, r: ([x * s + tx, y * s + ty, (x + w) * s + tx, (y + h) * s + ty], r * s)
    b, r = box(*PHONE); d.rounded_rectangle(b, r, fill=(255, 255, 255, 107))
    b, r = box(*TV); d.rounded_rectangle(b, r, fill=(255, 255, 255, 255))
    b, r = box(*STAND); d.rounded_rectangle(b, r, fill=(255, 255, 255, 255))
    b, r = box(*PIC)
    grad = Image.linear_gradient("L").rotate(90).resize((int(b[2] - b[0]), int(b[3] - b[1])))
    pic = Image.composite(Image.new("RGBA", grad.size, hexrgb("#A78BFA") + (255,)), Image.new("RGBA", grad.size, hexrgb("#7C3AED") + (255,)), grad)
    m = Image.new("L", grad.size, 0); ImageDraw.Draw(m).rounded_rectangle([0, 0, grad.size[0] - 1, grad.size[1] - 1], r, fill=255)
    over.paste(pic, (int(b[0]), int(b[1])), m)
    img.paste(over, (0, 0), over)


def png(path, w, h, theme, draw):
    k = 4
    img = bg_image(w * k, h * k, theme).convert("RGBA")
    draw(img, k)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.resize((w, h), Image.LANCZOS).convert("RGB").save(path)


def lockup(img, k, w, h, size, subtitle=None, tagline=None):
    _, word_w = text_path("Beamsy", BOLD, size * k, 0, 0)
    cap = cap_height(BOLD, size * k)
    s = cap * 1.25 / 78  # mark content a bit taller than the capitals
    mark_w = 78 * s
    gap = size * k * 0.2
    x0 = (w * k - (mark_w + gap + word_w)) / 2
    extra = (size * k * 0.42 if tagline else 0)
    top = (h * k - max(mark_w, cap) - extra) / 2
    draw_mark(img, s, x0 - 10 * s, top + (max(mark_w, cap) - mark_w) / 2 - 10 * s)
    base = top + (max(mark_w, cap) + cap) / 2
    draw_text(img, (x0 + mark_w + gap, base), "Beamsy", BOLD, size * k)
    if subtitle:
        draw_text(img, (x0 + mark_w + gap + size * k * 0.03, base + size * k * 0.42), subtitle, MEDIUM, size * k * 0.34, fill=(255, 255, 255, 220), tracking=0)
    if tagline:
        draw_text(img, (w * k / 2, base + size * k * 0.62), tagline, MEDIUM, size * k * 0.3, fill=(255, 255, 255, 225), anchor="ms", tracking=0)


